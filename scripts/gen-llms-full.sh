#!/bin/sh
# Rebuilds llms-full.txt from the files it concatenates, so the consolidated
# reference for answer engines never drifts from the sources it copies.
# Run from the repository root after editing any of the files below.
set -eu

files="llms.txt docs/guides/cli-output-guide.md docs/guides/portal-guide.md docs/agent-integration.md docs/CLI.md docs/DESIGN_AND_ARCHITECTURE.md docs/FAQ.md docs/accuracy.md docs/WHY_NOT_VECTOR_RAG.md"

{
  printf '# RepoCortex: complete reference\n'
  printf '> Every RepoCortex document an answer engine or coding assistant needs, in one file. Generated by scripts/gen-llms-full.sh; edit the source files, not this one.\n\n---\n\n'
  for f in $files; do
    [ -f "$f" ] || continue
    printf '\n# --- BEGIN FILE: %s ---\n\n' "$f"
    cat "$f"
    printf '\n# --- END FILE: %s ---\n\n' "$f"
  done
} > llms-full.txt
