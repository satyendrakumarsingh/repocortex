#!/usr/bin/env bash
# Renders the Homebrew formula for one release from that release's SHA256SUMS.
#
#   scripts/release/render-homebrew-formula.sh v1.0.1 dist/SHA256SUMS > repocortex.rb
#
# The formula in satyendrakumarsingh/homebrew-tap used to be edited by hand:
# version, four URLs and four checksums per release. After v1.0.1 it still
# named the old `cortex` binary and pointed at v1.0.0. The release job runs
# this script and opens the bump; packaging/homebrew/repocortex.rb is its
# output for the current release, kept here so a change to the template is
# reviewed as a change to the formula.
#
# It refuses rather than writes a formula with a missing checksum: a formula
# that cannot verify its download fails for every user who installs it.
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <tag, e.g. v1.0.1> <SHA256SUMS file>" >&2
  exit 2
fi
tag=$1
sums=$2

if ! [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "$0: $tag is not a release tag (vMAJOR.MINOR.PATCH); a pre-release is not published to Homebrew" >&2
  exit 2
fi
if [ ! -r "$sums" ]; then
  echo "$0: cannot read $sums" >&2
  exit 2
fi
version=${tag#v}
base="https://github.com/satyendrakumarsingh/repocortex/releases/download/${tag}"

sum_of() {
  local file="repocortex_${tag}_$1.tar.gz" sum
  sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if ! [[ "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "$0: no SHA-256 for $file in $sums" >&2
    exit 1
  fi
  printf '%s' "$sum"
}

darwin_arm64=$(sum_of darwin_arm64)
darwin_amd64=$(sum_of darwin_amd64)
linux_arm64=$(sum_of linux_arm64)
linux_amd64=$(sum_of linux_amd64)

cat <<EOF
# Generated by scripts/release/render-homebrew-formula.sh from the ${tag} SHA256SUMS.
class Repocortex < Formula
  desc "Local code graph for AI coding agents, served over MCP, a CLI and REST"
  homepage "https://github.com/satyendrakumarsingh/repocortex"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    if Hardware::CPU.arm?
      url "${base}/repocortex_${tag}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    else
      url "${base}/repocortex_${tag}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "${base}/repocortex_${tag}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    else
      url "${base}/repocortex_${tag}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "repocortex"
  end

  test do
    assert_match "repocortex", shell_output("#{bin}/repocortex version")
    system bin/"repocortex", "languages"
  end
end
EOF
