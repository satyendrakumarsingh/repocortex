package cli

// The dependency inventory is generated, not written. A hand-maintained list
// is wrong within a month and nobody notices, because nothing checks it. This
// makes the file a build output and `--check` makes CI the thing that notices.

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
)

// thirdPartyFile is the inventory's path, relative to the repository root.
const thirdPartyFile = "THIRD_PARTY.md"

// moduleInfo is the slice of `go list -m -json all` this inventory needs.
type moduleInfo struct {
	Path    string `json:"Path"`
	Version string `json:"Version"`
	Main    bool   `json:"Main"`
	// Indirect modules are still shipped in the binary, so they are listed.
	Indirect bool `json:"Indirect"`
}

// listModules returns every module in the build graph except the main module.
func listModules(root string) ([]moduleInfo, error) {
	cmd := exec.Command("go", "list", "-m", "-json", "all")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list -m: %w", err)
	}

	var mods []moduleInfo
	dec := json.NewDecoder(strings.NewReader(string(out)))
	for dec.More() {
		var m moduleInfo
		if err := dec.Decode(&m); err != nil {
			return nil, fmt.Errorf("decode go list output: %w", err)
		}
		if m.Main || m.Version == "" {
			continue
		}
		mods = append(mods, m)
	}
	return mods, nil
}

// renderThirdParty produces the inventory. Sorted by module path so the output
// is byte-identical across runs and a diff means a real dependency change.
func renderThirdParty(mods []moduleInfo) string {
	sorted := make([]moduleInfo, len(mods))
	copy(sorted, mods)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })

	var b strings.Builder
	b.WriteString("# Third-party dependencies\n\n")
	b.WriteString("Generated by `repocortex licenses`. Do not edit by hand —\n")
	b.WriteString("CI asserts this file matches the module graph.\n\n")
	b.WriteString("Every module below is compiled into the released binary.\n")
	b.WriteString("Consult each module's own repository for its licence text.\n\n")
	b.WriteString("| Module | Version | Direct |\n")
	b.WriteString("|---|---|---|\n")
	for _, m := range sorted {
		direct := "yes"
		if m.Indirect {
			direct = "no"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", m.Path, m.Version, direct)
	}
	return b.String()
}

func newLicensesCmd(g *Global) *cobra.Command {
	var check bool
	cmd := &cobra.Command{
		Use:   "licenses",
		Short: "Regenerate the third-party dependency inventory",
		Long: `Writes THIRD_PARTY.md from the module graph.

With --check, verifies the committed file is current and exits non-zero if
it is not. That is the form CI runs.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			root := g.Config().RepoRoot
			mods, err := listModules(root)
			if err != nil {
				return err
			}
			want := renderThirdParty(mods)
			path := filepath.Join(root, thirdPartyFile)

			if check {
				have, err := os.ReadFile(path) // #nosec G304 -- path is repo-root relative and constant
				if err != nil {
					return fmt.Errorf("read %s: %w", thirdPartyFile, err)
				}
				if string(have) != want {
					return fmt.Errorf("%s is stale; run: repocortex licenses", thirdPartyFile)
				}
				fmt.Fprintf(cmd.OutOrStdout(), "%s is current (%d modules)\n", thirdPartyFile, len(mods))
				return nil
			}

			if err := os.WriteFile(path, []byte(want), 0o600); err != nil {
				return fmt.Errorf("write %s: %w", thirdPartyFile, err)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %s (%d modules)\n", thirdPartyFile, len(mods))
			return nil
		},
	}
	cmd.Flags().BoolVar(&check, "check", false, "verify the committed file is current instead of writing it")
	return cmd
}
